// Turns google-services.json into the resources firebase_core reads.
//
// Applied only when the file is present: declaring it in `plugins {}`
// unconditionally hard-fails the build wherever there is no Firebase project,
// and the file is gitignored — so a fresh clone has to keep building. Without
// it the app simply gets no push token, which `PushService` already treats as
// an ordinary, permanent state: reminders still schedule on the device and
// broadcasts still land in the in-app inbox.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

